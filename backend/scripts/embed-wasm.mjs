// Embeds the alibi-core WebAssembly module into a TypeScript source file so the Convex bundler
// ships it with the node actions. Run after `cargo build --release -p alibi-wasm --target wasm32-unknown-unknown`.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const src = new URL("../../target/wasm32-unknown-unknown/release/alibi_wasm.wasm", import.meta.url);
const bytes = readFileSync(src);
const sha = createHash("sha256").update(bytes).digest("hex");
writeFileSync(
  new URL("../convex/lib/wasmBytes.ts", import.meta.url),
  `"use node";\n// Generated by scripts/embed-wasm.mjs from crates/alibi-wasm. Do not edit.\n` +
    `export const WASM_SHA256 = "${sha}";\n` +
    `export const WASM_BASE64 =\n  "${bytes.toString("base64")}";\n`,
);
console.log(`embedded ${bytes.length} bytes, sha256 ${sha}`);
